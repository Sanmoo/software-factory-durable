import assert from 'node:assert/strict';
import { test } from 'node:test';
import type { SourceTriage, TriageRequest } from '../../src/control/types.js';
import type { JiraTriageWrite } from '../../src/issue-tracker/index.js';
import { card, jiraSource, relabel, type JiraCard, type JiraRemote } from './jira-doubles.js';
import { call, trackerWrites, triageWorld } from './triage-investigation-fixture.js';

// Spec #68 §8 (ticket #78): a recorded Verdict is published on its Jira Card. Real Control, SQLite and Triager session under a scripted
// provider; Jira is the double, which applies each write as the Factory's account would (a changelog entry with the request's mark) and
// can lose, refuse, retain or anonymize one. The source routes component 10022 to acme/project and 10021 to acme/other.
const triage: SourceTriage = { needsTriage: 'needs-triage', needsInfo: 'needs-info', readyForHuman: 'ready-for-human', wontfix: 'wontfix', available: true };
const text = 'Observado: o vencimento ignora feriados.\nInferido: falta a regra de feriado.\n\nAção: corrigir o cálculo.';
/** An open Card carrying `needs-triage` beside a label and a component the Factory never touches. */
function triageCard(overrides: Partial<JiraCard> = {}): JiraCard {
  const item = card('81017', 'PAG-42', { labels: ['squad-pagamentos'], components: ['10022', '10099'], statusCategory: 'indeterminate', ...overrides });
  relabel(item, { add: ['needs-triage'] });
  return item;
}
type World = Awaited<ReturnType<typeof triageWorld>>;
type Recorded = { component?: string; card?: Partial<JiraCard>; remote?: Partial<JiraRemote>; during?: (item: JiraCard) => void };
/** A world whose first request has its Verdict recorded and nothing published yet. */
async function recorded(t: Parameters<typeof triageWorld>[0], outcome: string, options: Recorded = {}) {
  const item = triageCard(options.card);
  const w = await triageWorld(t, {
    jira: { cards: [item], ...options.remote },
    sources: [jiraSource({ triage })],
    script: [
      () => {
        options.during?.(item);
        return call('concluir_triagem', { outcome, category: 'bug', text, ...(options.component ? { component: options.component } : {}) });
      },
    ],
  });
  await w.start();
  assert.equal((await w.investigated()).state, 'publishing');
  return { w, item };
}
const writes = (w: World) => w.jira.calls.filter(item => item.method === 'writeTriage').map(item => (item.args as { write: JiraTriageWrite }).write);
const kinds = (w: World) =>
  writes(w).map(write =>
    write.kind === 'comment' ? 'comment' : `edit +${write.addLabels.join(',')} -${write.removeLabels.join(',')} components:${write.addComponents.join(',')}`,
  );
const only = async (w: World): Promise<TriageRequest> => (await w.requests())[0]!;
const statuses = (request: TriageRequest) => request.intended!.map(effect => effect.status);
const comments = (w: World) => w.jira.comments['81017'] ?? [];
const edited = (item: JiraCard) => [[...item.labels].sort(), item.components, item.statusCategory];

for (const [outcome, label] of [
  ['ready-for-agent', 'factory-ready'],
  ['needs-info', 'needs-info'],
  ['ready-for-human', 'ready-for-human'],
  ['wontfix', 'wontfix'],
] as const)
  test(`TR-15 (Jira): ${outcome} is published as one comment and then ONE edit, with nothing else changed on the Card`, async t => {
    const { w, item } = await recorded(t, outcome);
    await w.poll();
    const request = await only(w);
    assert.deepEqual([request.state, request.end?.code], ['concluded', 'VERDICT_PUBLISHED']);
    assert.deepEqual(kinds(w), ['comment', `edit +${label} -needs-triage components:`]);
    assert.deepEqual(
      trackerWrites(w.jira.methods()).filter(method => method !== 'writeTriage'),
      [],
      'no transition, assignee, resolution or any other kind of write',
    );
    assert.deepEqual(edited(item), [[label, 'squad-pagamentos'].sort(), ['10022', '10099'], 'indeterminate'], 'wontfix does not transition the Card');
    assert.ok(statuses(request).every(status => status === 'confirmed'));
    const [published] = comments(w);
    assert.equal(comments(w).length, 1);
    assert.ok(published!.text!.startsWith(`<!-- software-factory:triage:${request.triage_request_id} -->\n**Triage Verdict, generated by AI.**`));
    assert.ok(published!.text!.endsWith(text), 'the Verdict text is published whole');
    assert.equal(request.intended![0]!.reference, `https://equipe.atlassian.net/browse/PAG-42?focusedCommentId=${published!.commentId}`);
    assert.equal(w.bodies.length, 1, 'the publication never calls the model');
    await w.poll();
    assert.equal(writes(w).length, 2, 'a concluded request writes nothing more');
  });

test('TR-17: a Card without a routed component gets the component the Triager identified in the same edit as the label', async t => {
  const { w, item } = await recorded(t, 'ready-for-agent', { component: '10022', card: { components: ['10099'] } });
  await w.poll();
  const request = await only(w);
  assert.deepEqual([request.state, request.verdict?.outcome, request.verdict?.fallback], ['concluded', 'ready-for-agent', undefined]);
  assert.deepEqual(kinds(w), ['comment', 'edit +factory-ready -needs-triage components:10022']);
  assert.deepEqual(edited(item), [['factory-ready', 'squad-pagamentos'], ['10099', '10022'], 'indeterminate'], 'no component is removed');
  assert.deepEqual(statuses(request), ['confirmed', 'confirmed', 'confirmed', 'confirmed']);
  assert.match(comments(w)[0]!.text!, /the same edit adds the component 10022, which routes to the repository `acme\/project`/);
});

test('TR-17: a Card that already routes to the repository of the identified component is labelled with no component written', async t => {
  const { w, item } = await recorded(t, 'ready-for-agent', { component: '10022' });
  await w.poll();
  const request = await only(w);
  assert.deepEqual([request.state, request.intended!.map(effect => effect.kind)], ['concluded', ['comment', 'add-label', 'remove-label']]);
  assert.deepEqual(kinds(w), ['comment', 'edit +factory-ready -needs-triage components:']);
  assert.deepEqual(item.components, ['10022', '10099']);
});

for (const [name, code, options, suggestion] of [
  ['the components of the Card route to two repositories', 'TRIAGE_ROUTE_DIVERGENT', { card: { components: ['10022', '10021'] } }, /suggested no component/],
  [
    'the identified component routes elsewhere than the Card',
    'TRIAGE_ROUTE_DIVERGENT',
    { card: { components: ['10021'] }, component: '10022' },
    /Suggested component: 10022, which routes to the repository `acme\/project`/,
  ],
  [
    'the Triager identified no component for an unrouted Card',
    'TRIAGE_COMPONENT_NOT_IDENTIFIED',
    { card: { components: ['10099'] } },
    /suggested no component/,
  ],
  [
    'the components of the Card are not readable',
    'TRIAGE_COMPONENTS_UNREADABLE',
    { component: '10021', during: (item: JiraCard) => void (item.components = null) },
    /Suggested component: 10021, which routes to the repository `acme\/other`/,
  ],
] as const)
  test(`TR-17: ready-for-agent falls to needs-info, with the suggestion in the comment, when ${name}`, async t => {
    const { w, item } = await recorded(t, 'ready-for-agent', options as Recorded);
    const before = item.components === null ? null : [...item.components];
    await w.poll();
    const request = await only(w);
    assert.deepEqual([request.state, request.verdict?.outcome], ['concluded', 'needs-info']);
    assert.deepEqual(
      [request.verdict?.fallback?.from, request.verdict?.fallback?.code, request.verdict?.fallback?.afterComment],
      ['ready-for-agent', code, false],
    );
    assert.deepEqual(kinds(w), ['comment', 'edit +needs-info -needs-triage components:'], 'ready-for-agent is never applied without a single route');
    assert.deepEqual([[...item.labels].sort(), item.components], [['needs-info', 'squad-pagamentos'], before], 'no component is added or removed');
    const [published] = comments(w);
    assert.equal(comments(w).length, 1);
    assert.match(published!.text!, /\*\*Outcome:\*\* `needs-info`/);
    assert.match(published!.text!, /The Factory applies `needs-info` instead because /);
    assert.match(published!.text!, suggestion);
    assert.ok(request.timeline.some(entry => entry.event === 'outcome-fallback' && entry.code === code));
  });

for (const fault of ['forbidden', 'rejected'] as const)
  test(`TR-17: when Jira refuses the edit that adds the component (${fault}), needs-info is applied instead and the one comment already says so`, async t => {
    const options = { component: '10022', card: { components: ['10099'] }, remote: { triageWrites: [undefined, fault] } };
    const { w, item } = await recorded(t, 'ready-for-agent', options);
    await w.poll();
    const request = await only(w);
    assert.deepEqual([request.state, request.verdict?.outcome], ['concluded', 'needs-info']);
    const fallback = request.verdict!.fallback!;
    assert.deepEqual(
      [fallback.code, fallback.afterComment, fallback.componentId, fallback.repository, fallback.observed],
      ['TRIAGE_COMPONENT_NOT_WRITTEN', true, '10022', 'acme/project', fault === 'forbidden' ? 'JIRA_FORBIDDEN' : 'JIRA_REQUEST_REJECTED'],
    );
    assert.deepEqual(kinds(w), ['comment', 'edit +factory-ready -needs-triage components:10022', 'edit +needs-info -needs-triage components:']);
    assert.deepEqual(edited(item), [['needs-info', 'squad-pagamentos'], ['10099'], 'indeterminate']);
    assert.deepEqual(statuses(request), ['confirmed', 'confirmed', 'confirmed']);
    assert.equal(comments(w).length, 1, 'never a second comment');
    assert.match(comments(w)[0]!.text!, /If Jira refuses that edit, the Factory applies `needs-info` instead of `factory-ready`/);
    assert.match(comments(w)[0]!.text!, /adds the component 10022, which routes to the repository `acme\/project`/);
  });

test('TR-17: an edit that fails for a passing reason is sent again as it was, with the component', async t => {
  const { w, item } = await recorded(t, 'ready-for-agent', { component: '10022', card: { components: [] }, remote: { triageWrites: [undefined, 'failed'] } });
  await w.poll();
  let request = await only(w);
  assert.deepEqual([request.state, request.verdict?.outcome, request.publication?.hold?.code], ['publishing', 'ready-for-agent', 'JIRA_RATE_LIMITED']);
  await w.poll();
  request = await only(w);
  assert.deepEqual([request.state, request.verdict?.fallback, item.components], ['concluded', undefined, ['10022']]);
});

test('TR-13 (Jira): needs-triage withdrawn during the investigation leaves one informative comment and an abandoned request', async t => {
  const { w, item } = await recorded(t, 'ready-for-agent', {
    component: '10022',
    card: { components: [] },
    during: card => relabel(card, { remove: ['needs-triage'] }),
  });
  await w.poll();
  const request = await only(w);
  assert.deepEqual([request.state, request.end?.code, request.publication?.mode], ['abandoned', 'NEEDS_TRIAGE_REMOVED', 'informative']);
  assert.deepEqual(kinds(w), ['comment'], 'no label and no component is changed');
  assert.deepEqual(statuses(request), ['confirmed', 'no-longer-allowed', 'no-longer-allowed', 'no-longer-allowed']);
  assert.deepEqual(edited(item), [['squad-pagamentos'], [], 'indeterminate']);
  assert.match(comments(w)[0]!.text!, /the Factory did not apply the outcome because `needs-triage` was removed/);
  await w.poll();
  assert.equal(comments(w).length, 1, 'never a second comment');
});

test('TR-19 (Jira): a comment that was created without an answer is recognised on the re-read and never repeated', async t => {
  const { w } = await recorded(t, 'needs-info', { remote: { triageWrites: ['unknown-applied'] } });
  await w.poll();
  assert.equal((await only(w)).state, 'concluded');
  assert.equal(comments(w).length, 1, 'never a duplicated comment');
  assert.deepEqual(kinds(w), ['comment', 'edit +needs-info -needs-triage components:'], 'only what is missing is written');
});

test('TR-19 (Jira): a comment that was not created and got no answer is written again only after a later read shows none', async t => {
  const { w } = await recorded(t, 'needs-info', { remote: { triageWrites: ['unknown-not-applied'] } });
  await w.poll();
  let request = await only(w);
  assert.deepEqual([request.state, request.publication?.hold?.code, kinds(w)], ['publishing', 'JIRA_TIMEOUT', ['comment']]);
  await w.poll();
  request = await only(w);
  assert.equal(request.state, 'concluded');
  assert.equal(comments(w).length, 1, 'never a duplicated comment');
});

test('TR-19 (Jira): an edit that was applied without an answer is recognised by the changelog as the Factory’s own and not repeated', async t => {
  const { w, item } = await recorded(t, 'ready-for-agent', {
    component: '10022',
    card: { components: [] },
    remote: { triageWrites: [undefined, 'unknown-applied'] },
  });
  await w.poll();
  assert.equal((await only(w)).state, 'concluded');
  assert.deepEqual(kinds(w), ['comment', 'edit +factory-ready -needs-triage components:10022']);
  assert.deepEqual(item.components, ['10022']);
});

for (const [fault, what] of [
  ['anonymous', 'a changelog entry without an author'],
  ['unmarked', 'an entry of the Factory’s account without the mark of the request'],
] as const)
  test(`TR-20 (Jira): an effect present with ${what} stops the publication with an Impediment`, async t => {
    const { w, item } = await recorded(t, 'needs-info', { remote: { triageWrites: [undefined, fault] } });
    await w.poll();
    let request = await only(w);
    assert.deepEqual([request.state, statuses(request)], ['publishing', ['confirmed', 'ambiguous-authorship', 'ambiguous-authorship']]);
    const impediment = request.publication!.impediment!;
    assert.deepEqual([impediment.code, impediment.effects], ['TRIAGE_EFFECT_AUTHORSHIP_AMBIGUOUS', [1, 2]]);
    await w.poll();
    request = await only(w);
    assert.equal(request.publication!.impediment!.ref, impediment.ref, 'the same Impediment across passes');
    assert.equal(writes(w).length, 2, 'nothing is completed on the Factory’s own account');
    assert.deepEqual([...item.labels].sort(), ['needs-info', 'squad-pagamentos']);
  });

test('a label a person changes between the comment and the edit is never overwritten', async t => {
  const { w, item } = await recorded(t, 'needs-info', {
    remote: { afterTriageWrite: (write, card) => void (write.kind === 'comment' && relabel(card, { add: ['ready-for-human'] })) },
  });
  await w.poll();
  const request = await only(w);
  assert.deepEqual([request.state, request.end?.code, kinds(w)], ['abandoned', 'TRIAGE_LABELS_CHANGED', ['comment']]);
  assert.deepEqual([...item.labels].sort(), ['needs-triage', 'ready-for-human', 'squad-pagamentos'], 'the person’s change stands');
});
