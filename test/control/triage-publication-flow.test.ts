import assert from 'node:assert/strict';
import { test } from 'node:test';
import type { SourceTriage, TicketSource, TriageRequest } from '../../src/control/types.js';
import type { TriageWrite } from '../../src/issue-tracker/index.js';
import { applyLabel, closeIssue, remoteIssue, removeLabel, type Remote, type RemoteIssue } from './doubles.js';
import { call, trackerWrites, triageWorld } from './triage-investigation-fixture.js';

// Spec #68 §8 (ticket #77): a recorded Verdict is published on its GitHub issue. Real Control, SQLite and Triager session under a
// scripted provider; GitHub is the double, which applies each write as the App's bot would and can lose, retain or anonymize one.
const triage: SourceTriage = { needsTriage: 'needs-triage', needsInfo: 'needs-info', readyForHuman: 'ready-for-human', wontfix: 'wontfix', available: true };
const source: TicketSource = { tracker: 'github', repository: 'acme/project', discover: true, triage };
const text = 'Observado: o total ignora o cupom.\nInferido: falta a versão afetada.\nAção: informar a versão.';
/** An open issue carrying `needs-triage` beside labels the Factory never touches. */
function triageIssue(number = 7): RemoteIssue {
  const issue = remoteIssue(number, {
    labels: [
      { id: 91, name: 'bug' },
      { id: 92, name: 'area:cart' },
    ],
    title: 'Total errado',
    body: 'O total ignora o cupom.',
  });
  applyLabel(issue, 'needs-triage');
  return issue;
}
type World = Awaited<ReturnType<typeof triageWorld>>;
/** A world whose first request has its Verdict recorded and nothing published yet. */
async function recorded(
  t: Parameters<typeof triageWorld>[0],
  outcome: string,
  remote: Partial<Remote> = {},
  during?: (issue: RemoteIssue, github: Remote) => void,
) {
  const issue = triageIssue();
  const github: Remote = { issues: [issue], pulls: {}, ...remote };
  const w = await triageWorld(t, {
    github,
    sources: [source],
    script: [
      () => {
        during?.(issue, github);
        return call('concluir_triagem', { outcome, category: 'bug', text });
      },
    ],
  });
  await w.start();
  assert.equal((await w.investigated()).state, 'publishing');
  return { w, issue };
}
const writes = (w: World) => w.github.calls.filter(item => item.method === 'writeTriage').map(item => (item.args as { write: TriageWrite }).write);
const kinds = (w: World) =>
  writes(w).map(write => (write.kind === 'comment' ? 'comment' : write.kind === 'close' ? `close:${write.reason}` : `${write.kind}:${write.label}`));
const names = (issue: RemoteIssue) => issue.labels.map(label => label.name).sort();
const only = async (w: World): Promise<TriageRequest> => (await w.requests())[0]!;
const statuses = (request: TriageRequest) => request.intended!.map(effect => effect.status);
const comments = (w: World) => w.remote.comments?.[7] ?? [];

for (const [outcome, label, closes] of [
  ['ready-for-agent', 'ready-for-agent', false],
  ['needs-info', 'needs-info', false],
  ['ready-for-human', 'ready-for-human', false],
  ['wontfix', 'wontfix', true],
] as const)
  test(`TR-15 (GitHub) and TR-23: ${outcome} is published with the exact writes in order, by relative operation, with no model request`, async t => {
    const { w, issue } = await recorded(t, outcome);
    await w.poll();
    const request = await only(w);
    assert.deepEqual([request.state, request.end?.code], ['concluded', 'VERDICT_PUBLISHED']);
    assert.deepEqual(kinds(w), ['comment', `add-label:${label}`, 'remove-label:needs-triage', ...(closes ? ['close:not_planned'] : [])]);
    assert.deepEqual(
      trackerWrites(w.github.calls.map(item => item.method)).filter(method => method !== 'writeTriage'),
      [],
      'no other kind of write',
    );
    assert.deepEqual(names(issue), ['area:cart', 'bug', label].sort(), 'the other labels of the issue are untouched');
    assert.deepEqual([issue.state, issue.stateReason ?? null], closes ? ['closed', 'not_planned'] : ['open', null]);
    assert.deepEqual([issue.title, issue.body], ['Total errado', 'O total ignora o cupom.'], 'the body is never rewritten');
    assert.ok(statuses(request).every(status => status === 'confirmed'));
    const [published] = comments(w);
    assert.equal(comments(w).length, 1);
    assert.ok(published!.body.startsWith(`<!-- software-factory:triage:${request.triage_request_id} -->\n**Triage Verdict, generated by AI.**`));
    assert.ok(published!.body.endsWith(text), 'the Verdict text is published whole');
    assert.equal(request.intended![0]!.reference, published!.url, 'the published Verdict is kept as a link');
    assert.equal(w.bodies.length, 1, 'TR-23: the publication never calls the model');
    await w.poll();
    assert.equal(writes(w).length, closes ? 4 : 3, 'a concluded request writes nothing more');
  });

test('TR-16: a Ticket closed between the Verdict and the publication is abandoned with nothing written', async t => {
  const { w, issue } = await recorded(t, 'needs-info');
  closeIssue(issue);
  await w.poll();
  const request = await only(w);
  assert.deepEqual([request.state, request.end?.code], ['abandoned', 'TICKET_CLOSED']);
  assert.deepEqual(statuses(request), ['no-longer-allowed', 'no-longer-allowed', 'no-longer-allowed']);
  assert.deepEqual(writes(w), []);
  assert.equal(comments(w).length, 0);
});

test('TR-16: a Ticket that got a Work between the Verdict and the publication is abandoned with nothing written', async t => {
  // A person withdrew needs-triage and applied the admission label while the Triager was working: the normal admission creates the Work.
  const { w } = await recorded(t, 'needs-info', {}, issue => {
    removeLabel(issue, 'needs-triage');
    applyLabel(issue, 'ready-for-agent');
  });
  await w.poll();
  const request = await only(w);
  assert.deepEqual([request.state, request.end?.code], ['abandoned', 'WORK_EXISTS']);
  assert.deepEqual(writes(w), []);
});

test('TR-13 (GitHub): needs-triage withdrawn during the investigation leaves one informative comment and an abandoned request', async t => {
  const { w, issue } = await recorded(t, 'wontfix', {}, item => removeLabel(item, 'needs-triage'));
  await w.poll();
  const request = await only(w);
  assert.deepEqual([request.state, request.end?.code, request.publication?.mode], ['abandoned', 'NEEDS_TRIAGE_REMOVED', 'informative']);
  assert.deepEqual(kinds(w), ['comment'], 'no label is changed and nothing is closed');
  assert.deepEqual(statuses(request), ['confirmed', 'no-longer-allowed', 'no-longer-allowed', 'no-longer-allowed']);
  assert.deepEqual([names(issue), issue.state], [['area:cart', 'bug'], 'open']);
  assert.match(comments(w)[0]!.body, /the Factory did not apply the outcome because `needs-triage` was removed/);
  await w.poll();
  assert.equal(comments(w).length, 1, 'never a second comment');
});

test('TR-18: a cut between the outcome label and the withdrawal of needs-triage leaves a pair that is not a conflict', async t => {
  const { w, issue } = await recorded(t, 'needs-info', { triageWrites: [undefined, undefined, 'failed'] });
  await w.poll();
  let request = await only(w);
  assert.deepEqual([request.state, names(issue)], ['publishing', ['area:cart', 'bug', 'needs-info', 'needs-triage']]);
  assert.deepEqual([statuses(request), request.publication?.hold?.code], [['confirmed', 'confirmed', 'pending'], 'GITHUB_ACCESS_DENIED']);
  await w.poll();
  request = await only(w);
  assert.deepEqual([request.state, request.suspension, names(issue)], ['concluded', null, ['area:cart', 'bug', 'needs-info']]);
  assert.ok(!request.timeline.some(entry => entry.event === 'suspended'));
  assert.deepEqual(kinds(w), ['comment', 'add-label:needs-info', 'remove-label:needs-triage', 'remove-label:needs-triage']);
});

test('TR-19 (GitHub): a comment write that was applied without an answer is recognised on the re-read and never repeated', async t => {
  const { w } = await recorded(t, 'needs-info', { triageWrites: ['unknown-applied'] });
  await w.poll();
  const request = await only(w);
  assert.deepEqual([request.state, request.publication?.hold], ['concluded', null]);
  assert.equal(comments(w).length, 1, 'never a duplicated comment');
  assert.deepEqual(kinds(w), ['comment', 'add-label:needs-info', 'remove-label:needs-triage'], 'only what is missing is written');
});

test('TR-19 (GitHub): a comment write that was not applied and got no answer is written again only after a later read shows none', async t => {
  const { w } = await recorded(t, 'needs-info', { triageWrites: ['unknown-not-applied'] });
  await w.poll();
  let request = await only(w);
  assert.deepEqual([request.state, request.publication?.hold?.code, kinds(w)], ['publishing', 'GITHUB_TRANSPORT_UNAVAILABLE', ['comment']]);
  assert.deepEqual([statuses(request), request.intended![0]!.attempts], [['pending', 'pending', 'pending'], 1]);
  await w.poll();
  request = await only(w);
  assert.equal(request.state, 'concluded');
  assert.equal(comments(w).length, 1, 'never a duplicated comment');
  assert.deepEqual(kinds(w), ['comment', 'comment', 'add-label:needs-info', 'remove-label:needs-triage']);
});

test('TR-19 (GitHub): a label write that was applied without an answer is recognised as the Factory’s own and not repeated', async t => {
  const { w } = await recorded(t, 'needs-info', { triageWrites: [undefined, 'unknown-applied'] });
  await w.poll();
  assert.equal((await only(w)).state, 'concluded');
  assert.deepEqual(kinds(w), ['comment', 'add-label:needs-info', 'remove-label:needs-triage']);
});

test('TR-20 (GitHub): an effect present without an attributable author stops the publication with an Impediment', async t => {
  const { w, issue } = await recorded(t, 'needs-info', { triageWrites: [undefined, 'anonymous'] });
  await w.poll();
  let request = await only(w);
  assert.deepEqual([request.state, statuses(request)], ['publishing', ['confirmed', 'ambiguous-authorship', 'pending']]);
  const impediment = request.publication!.impediment!;
  assert.deepEqual([impediment.code, impediment.effects], ['TRIAGE_EFFECT_AUTHORSHIP_AMBIGUOUS', [1]]);
  assert.match(impediment.nextStep, /triage complete/);
  await w.poll();
  request = await only(w);
  assert.equal(request.publication!.impediment!.ref, impediment.ref, 'the same Impediment across passes');
  assert.deepEqual(kinds(w), ['comment', 'add-label:needs-info'], 'nothing is completed on the Factory’s own account');
  assert.deepEqual(names(issue), ['area:cart', 'bug', 'needs-info', 'needs-triage']);
});

test('TR-21: a label a person changes between two writes is never overwritten; the remaining effects are no longer allowed', async t => {
  const { w, issue } = await recorded(t, 'needs-info', {
    afterTriageWrite(write, item) {
      if (write.kind === 'comment') applyLabel(item, 'ready-for-human');
    },
  });
  await w.poll();
  const request = await only(w);
  assert.deepEqual([request.state, request.end?.code], ['abandoned', 'TRIAGE_LABELS_CHANGED']);
  assert.deepEqual(statuses(request), ['confirmed', 'no-longer-allowed', 'no-longer-allowed']);
  assert.deepEqual(kinds(w), ['comment']);
  assert.deepEqual(names(issue), ['area:cart', 'bug', 'needs-triage', 'ready-for-human'], 'the person’s change stands');
});

test('TR-23: a Control restarted with the request in publishing concludes it without a request to the provider', async t => {
  // The timeline becomes unreadable once the Verdict is being recorded: the publication cannot start in this run.
  const { w } = await recorded(t, 'ready-for-human', {}, (_issue, github) => void (github.labelHistoryFailure = { code: 'GITHUB_QUERY_FAILED' }));
  await w.poll();
  let request = await only(w);
  assert.deepEqual([request.state, request.publication?.hold?.code, writes(w).length], ['publishing', 'GITHUB_QUERY_FAILED', 0]);
  await w.stop();
  delete w.remote.labelHistoryFailure;
  await w.start();
  request = await only(w);
  assert.equal(request.state, 'concluded');
  assert.equal(request.attempts!.length, 1, 'the Triager is not activated again');
  assert.equal(w.bodies.length, 1, 'no request to the provider, whose script has no turn left');
});

test('TR-24: a label the API accepted and the confirming read does not show stays pending, and the request is not concluded', async t => {
  const { w, issue } = await recorded(t, 'needs-info', { triageWrites: [undefined, 'retained'] });
  await w.poll();
  let request = await only(w);
  assert.deepEqual([request.state, statuses(request)], ['publishing', ['confirmed', 'pending', 'pending']]);
  assert.deepEqual([request.intended![1]!.attempts, request.publication?.hold?.code], [1, 'TRIAGE_EFFECT_NOT_CONFIRMED']);
  assert.deepEqual(kinds(w), ['comment', 'add-label:needs-info'], 'needs-triage is not withdrawn before the outcome label is read back');
  assert.deepEqual(names(issue), ['area:cart', 'bug', 'needs-triage']);
  await w.poll();
  request = await only(w);
  assert.deepEqual([request.state, request.intended![1]!.attempts], ['concluded', 2]);
});

test('a label conflict on the re-read before the first write suspends the request; once it is gone the same Verdict is published', async t => {
  const { w, issue } = await recorded(t, 'needs-info');
  applyLabel(issue, 'wontfix');
  await w.poll();
  let request = await only(w);
  assert.deepEqual([request.state, request.suspension?.labels, writes(w).length], ['suspended', ['wontfix'], 0]);
  removeLabel(issue, 'wontfix');
  await w.poll();
  request = await only(w);
  assert.equal(request.state, 'concluded');
  assert.ok(request.timeline.some(entry => entry.event === 'publication-resumed'));
  assert.deepEqual([request.attempts!.length, w.bodies.length], [1, 1], 'the recorded Verdict is published as it is: no new investigation');
});
