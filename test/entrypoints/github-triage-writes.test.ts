import assert from 'node:assert/strict';
import { test } from 'node:test';
import { createGitHubAccess } from '../../src/platform/github/index.js';
import { createIssueTracker, type TicketRef } from '../../src/issue-tracker/index.js';
import { githubWorld, issue, worldScope, type World } from './github-world-fixture.js';

// Spec #68 §8 (ticket #77; TR-15): the writes of a Triage publication on a GitHub issue. I-local: real IssueTracker adapter, issuer and
// gh transport over the local world; NOT evidence of the real GitHub boundary (that is the `triage-qualification` recipe, TQ-05).
async function compose(t: Parameters<typeof githubWorld>[0], world: World) {
  const fixture = await githubWorld(t, world);
  const github = createGitHubAccess({ root: fixture.root, executable: fixture.executable, appId: 1, privateKeyFile: 'credentials/app.pem' });
  return { ...fixture, tracker: createIssueTracker({ github, scopes: [worldScope] }) };
}
const ticket: TicketRef = {
  tracker: 'github',
  repository: 'acme/project',
  repositoryId: 3,
  issueId: 7003,
  nodeId: 'I_node3',
  number: 3,
  url: 'https://github.com/acme/project/issues/3',
};
const labelled = () =>
  issue(3, {
    labels: [
      { id: 60, name: 'bug' },
      { id: 61, name: 'needs-triage' },
    ],
  });

test('TR-15: the four writes go as one comment, relative label operations and a not_planned closing, each under its own revoked issues:write grant', async t => {
  const world = await compose(t, { issues: [labelled()], pulls: [] });
  const body = '<!-- software-factory:triage:0b9c6a52-3d3e-4c8f-9a51-000000000077 -->\n**Triage Verdict, generated by AI.**';
  const commented = await world.tracker.writeTriage!(ticket, { kind: 'comment', body });
  assert.equal(commented.kind, 'accepted');
  assert.match((commented.kind === 'accepted' && commented.comment?.url) || '', /^https:\/\/github\.com\/acme\/project\/issues\/3#issuecomment-\d+$/);
  assert.equal((await world.tracker.writeTriage!(ticket, { kind: 'add-label', label: 'wontfix' })).kind, 'accepted');
  assert.equal((await world.tracker.writeTriage!(ticket, { kind: 'remove-label', label: 'needs-triage' })).kind, 'accepted');
  assert.equal((await world.tracker.writeTriage!(ticket, { kind: 'close', reason: 'not_planned' })).kind, 'accepted');

  const trace = await world.trace();
  const sent = trace.filter(entry => entry.method !== 'GET' && !entry.endpoint.includes('access_tokens') && entry.endpoint !== '/installation/token');
  assert.deepEqual(
    sent.map(entry => [entry.method, entry.endpoint, entry.request ?? entry.body]),
    [
      ['POST', '/repos/acme/project/issues/3/comments', body],
      ['POST', '/repos/acme/project/issues/3/labels', { labels: ['wontfix'] }],
      ['DELETE', '/repos/acme/project/issues/3/labels/needs-triage', undefined],
      ['PATCH', '/repos/acme/project/issues/3', { state: 'closed', state_reason: 'not_planned' }],
    ],
    'never a replacement of the label set, never the body, the title, the assignees or another field',
  );
  const grants = trace.filter(entry => entry.endpoint.includes('access_tokens') && entry.permissions?.issues === 'write');
  assert.equal(grants.length, 4, 'one single-use grant per write');
  assert.ok(grants.every(entry => JSON.stringify(entry.permissions) === JSON.stringify({ metadata: 'read', issues: 'write' })));
  assert.equal(trace.filter(entry => entry.endpoint === '/installation/token' && entry.method === 'DELETE').length >= 4, true, 'each grant is revoked');

  // What a later read shows: the labels by relative operation, the closing, and the App as the author of each change.
  const read = await world.tracker.readTicket(ticket);
  assert.deepEqual(read.kind === 'observed' && [read.state, read.stateReason, read.labels.map(label => label.name).sort()], [
    'closed',
    'not_planned',
    ['bug', 'wontfix'],
  ]);
  const history = await world.tracker.readLabelHistory!(ticket);
  assert.equal(history.kind, 'observed');
  if (history.kind !== 'observed') return;
  assert.deepEqual(
    history.events.map(event => [event.action, event.label, event.ownApp, event.viaApp]),
    [
      ['added', 'wontfix', true, 1],
      ['removed', 'needs-triage', true, 1],
    ],
  );
  assert.deepEqual(
    history.closures.map(event => [event.action, event.ownApp]),
    [['closed', true]],
  );
  const comments = await world.tracker.readTicketComments!(ticket);
  assert.deepEqual(comments.kind === 'observed' && comments.comments.map(comment => [comment.body, comment.ownApp]), [[body, true]]);
});

test('TR-20: a timeline change whose author GitHub does not name, or made by a person, is never reported as the App’s own', async t => {
  const human = { id: 9, login: 'human', type: 'User' };
  const at = '2026-11-20T10:00:00Z';
  const world = await compose(t, {
    issues: [
      issue(3, {
        timeline: [
          { id: 11, event: 'labeled', label: { name: 'wontfix' }, created_at: at, actor: null, performed_via_github_app: null },
          { id: 12, event: 'closed', created_at: at, actor: human, performed_via_github_app: null },
          { id: 13, event: 'reopened', created_at: at, actor: human, performed_via_github_app: { id: 1 } },
        ],
      }),
    ],
    pulls: [],
  });
  const history = await world.tracker.readLabelHistory!(ticket);
  assert.equal(history.kind, 'observed');
  if (history.kind !== 'observed') return;
  assert.deepEqual(
    history.events.map(event => [event.actor, event.ownApp]),
    [[null, false]],
  );
  assert.deepEqual(
    history.closures.map(event => [event.eventId, event.action, event.actor?.login, event.ownApp]),
    [
      ['12', 'closed', 'human', false],
      ['13', 'reopened', 'human', false],
    ],
  );
});

test('TR-19: a write GitHub answers with a server error is of unknown outcome; one it refuses, or an unconfigured repository, changed nothing', async t => {
  const world = await compose(t, { issues: [labelled()], pulls: [], triageFault: { status: 502, applied: true } });
  const unknown = await world.tracker.writeTriage!(ticket, { kind: 'add-label', label: 'wontfix' });
  assert.equal(unknown.kind, 'unknown', 'the label may be there: the Control reads the issue before anything else');
  const refusing = await compose(t, { issues: [labelled()], pulls: [], triageFault: { status: 422, applied: false } });
  const refused = await refusing.tracker.writeTriage!(ticket, { kind: 'close', reason: 'not_planned' });
  assert.equal(refused.kind, 'failed');
  const foreign = await world.tracker.writeTriage!({ ...ticket, repository: 'acme/elsewhere' }, { kind: 'add-label', label: 'wontfix' });
  assert.deepEqual([foreign.kind, foreign.kind === 'failed' && foreign.code], ['failed', 'REPOSITORY_NOT_CONFIGURED']);
  const absent = await refusing.tracker.writeTriage!(ticket, { kind: 'remove-label', label: 'not there' });
  assert.equal(absent.kind, 'failed', 'removing a label the issue does not carry is a known failure');
});
