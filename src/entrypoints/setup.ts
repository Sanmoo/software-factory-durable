import { lstat, mkdir, readFile, realpath, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { userInfo } from 'node:os';
import { isAbsolute, join, resolve } from 'node:path';
import { openSync, closeSync, writeSync, constants } from 'node:fs';
import { isatty } from 'node:tty';
import { createRecords } from '../records/index.js';
import { firstFactoryOAuthLogin } from '../workers/index.js';

const directories = ['releases', 'assets', 'credentials', 'data', 'environments', 'run'];
const initialConfiguration = `# Complete explicit operators, models and GitHub App references before operation.
# No repositories are authorized by setup. Never put secret values in this file.
schemaVersion: 1
operators: []
models:
  builder: { provider: null, model: null }
  standards: { provider: null, model: null }
  spec: { provider: null, model: null }
githubApp:
  appId: null
  privateKeyFile: credentials/github-app.pem
sandbox:
  schemaVersion: 1
  profile: gondolin-qemu-alpine-dev-v1
repositories: []
`;

export async function setup(root: string): Promise<{ root: string; created: string[] }> {
  await mkdir(root, { recursive: true, mode: 0o700 });
  const canonicalRoot = await realpath(root);
  // Preflight every known path before creating children; never follow/repair unknown content.
  for (const name of [...directories, 'config.yaml']) {
    try {
      const info = await lstat(join(canonicalRoot, name));
      if (info.isSymbolicLink() || (name === 'config.yaml' ? !info.isFile() : !info.isDirectory())) {
        throw new Error(`Unsafe installation path: ${name}`);
      }
    } catch (error) {
      if (!(error instanceof Error && 'code' in error && error.code === 'ENOENT')) throw error;
    }
  }
  const created: string[] = [];
  for (const name of directories) {
    try {
      await mkdir(join(canonicalRoot, name), { mode: 0o700 });
      created.push(name);
    } catch (error) {
      if (!(error instanceof Error && 'code' in error && error.code === 'EEXIST')) throw error;
      const existing = await lstat(join(canonicalRoot, name));
      if (!existing.isDirectory() || existing.isSymbolicLink()) throw new Error(`Unsafe installation path: ${name}`);
    }
  }
  try {
    await writeFile(join(canonicalRoot, 'config.yaml'), initialConfiguration, { flag: 'wx', mode: 0o600 });
    created.push('config.yaml');
  } catch (error) {
    if (!(error instanceof Error && 'code' in error && error.code === 'EEXIST')) throw error;
  }
  return { root: canonicalRoot, created };
}

/**
 * Optional controller user service (spec §11.1), written ONLY on explicit request (`setup --service`) and never started, enabled or
 * reloaded: registration with systemd stays an explicit administrator step. It runs the SAME installation launcher as the foreground
 * `factory run`, hence the same controller and stable storage lock; it grants no extra privilege (workers never get host administration).
 */
export function serviceDefinition(root: string) {
  if (!/^\/[A-Za-z0-9._/-]+$/.test(root) || root.includes('//') || root.split('/').some(part => part === '.' || part === '..'))
    throw new Error('SERVICE_PATH_UNSUPPORTED');
  const unit = `software-factory-${createHash('sha256').update(root).digest('hex').slice(0, 12)}.service`;
  const text = `# Generated by \`factory setup --service\` for ${root}. Not started or enabled by setup.
# Register explicitly: systemctl --user daemon-reload && systemctl --user start ${unit}
[Unit]
Description=Software Factory controller (${root})

[Service]
Type=exec
WorkingDirectory=${root}
ExecStart=${root}/factory run
KillMode=mixed
KillSignal=SIGTERM
TimeoutStopSec=120
Restart=no
UMask=0077
NoNewPrivileges=yes

[Install]
WantedBy=default.target
`;
  return { unit, text };
}

/** The account's standard systemd user unit directory, from the account database (passwd), never from HOME or XDG_CONFIG_HOME. */
export function standardServiceDirectory(): string {
  return join(userInfo().homedir, '.config', 'systemd', 'user');
}

export async function setupService(root: string, directory?: string): Promise<{ unit: string; path: string; state: 'created' | 'preserved' }> {
  const { unit, text } = serviceDefinition(root);
  // Explicit absolute directory (operator/tests) or the account's standard systemd user path; never an environment-selected one.
  if (directory !== undefined && (!isAbsolute(directory) || resolve(directory) !== directory)) throw new Error('SERVICE_DIRECTORY_UNSUPPORTED');
  const target = directory ?? standardServiceDirectory();
  await mkdir(target, { recursive: true, mode: 0o700 });
  const path = join(target, unit);
  try {
    await writeFile(path, text, { flag: 'wx', mode: 0o600 });
    return { unit, path, state: 'created' };
  } catch (error) {
    if (!(error instanceof Error && 'code' in error && error.code === 'EEXIST')) throw error;
    const existing = await lstat(path);
    // An existing definition is never overwritten: identical is preserved, anything else is an explicit conflict.
    if (!existing.isFile() || existing.isSymbolicLink() || (await readFile(path, 'utf8')) !== text) throw new Error('SERVICE_UNIT_CONFLICT');
    return { unit, path, state: 'preserved' };
  }
}

/** Human-only terminal adapter. No authorization URLs go through process stdio,
 * Records, JSONL or sessions; no browser opener and no input/code capture. */
export async function firstHumanLogin(root: string): Promise<number> {
  let terminal: number | undefined;
  const controller = new AbortController();
  const cancel = () => controller.abort();
  try {
    if (process.stdin.isTTY !== true) throw new Error('TTY_REQUIRED');
    terminal = openSync('/dev/tty', constants.O_WRONLY | constants.O_NOCTTY);
    if (!isatty(terminal)) throw new Error('TTY_REQUIRED');
    const fd = terminal;
    process.on('SIGINT', cancel);
    process.on('SIGTERM', cancel);
    const records = await createRecords({ root }); // Register-only: no events/session/output capture.
    await firstFactoryOAuthLogin({
      factoryRoot: root,
      records,
      signal: controller.signal,
      tty: {
        isTTY: true,
        authorizationURL(url) {
          writeSync(fd, `Open this authorization URL in your browser on this host. Do not paste codes or URLs here.\n${url}\n`);
        },
      },
    });
    writeSync(fd, 'Factory OAuth credential created. Model access and runtime operation are not qualified.\n');
    return 0;
  } catch {
    // Never serialize any native error, cause, stack, URL or response body.
    if (terminal !== undefined) {
      try {
        writeSync(terminal, 'Factory OAuth login unavailable. No automatic repair or retry.\n');
      } catch {
        /* Closed. */
      }
    }
    return 2;
  } finally {
    process.off('SIGINT', cancel);
    process.off('SIGTERM', cancel);
    if (terminal !== undefined) {
      try {
        closeSync(terminal);
      } catch {
        /* Never expose raw terminal errors. */
      }
    }
  }
}
